"""Generate build_info.py for a build (version + short git commit)."""

import datetime
import os
import subprocess
import sys

BASE_VERSION = "1.0"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def git(*args):
    return subprocess.check_output(
        ["git", *args], cwd=ROOT, text=True, timeout=10).strip()


def main():
    try:
        count = int(git("rev-list", "--count", "HEAD"))
        commit = git("rev-parse", "--short", "HEAD")
        commit_date = git("show", "-s", "--format=%cI", "HEAD")
        version = "%s.%d" % (BASE_VERSION, count)
    except Exception as error:
        print("git info unavailable: %s" % error, file=sys.stderr)
        version = "%s.0" % BASE_VERSION
        commit = ""
        commit_date = ""
    build_date = datetime.date.today().isoformat()
    path = os.path.join(ROOT, "build_info.py")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write('"""Generated by tools/make_build_info.py."""\n')
        handle.write("VERSION = %r\n" % version)
        handle.write("COMMIT = %r\n" % commit)
        handle.write("BUILD_DATE = %r\n" % build_date)
        handle.write("COMMIT_DATE = %r\n" % commit_date)
    print("build_info.py: %s (%s)" % (version, commit or "no commit"))


if __name__ == "__main__":
    main()
